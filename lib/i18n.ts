export function translate(text: string, language: Language): string {
  if (language === "en") return text;
  if (sw[text]) return sw[text];
  const trimmed = text.trim();
  if (sw[trimmed]) return text.replace(trimmed, sw[trimmed]);
  const action = text.match(/^(budget|goal|debt|recurring) (created|updated)$/);
  if (action)
    return `${sw[action[1]]} ${action[2] === "created" ? "imeundwa" : "imehaririwa"}`;
  const creation = text.match(
    /^(Create|Edit) (budget|goal|debt|recurring|account|category)$/,
  );
  if (creation) return `${sw[creation[1]]} ${sw[creation[2]]}`;
  const schedule=text.match(/^(.+) · next due (\d{4}-\d{2}-\d{2})$/);if(schedule)return `${sw[schedule[1]]||schedule[1]} · malipo yanayofuata ${schedule[2]}`;
  const target=text.match(/^Target \/ due date: (.+)$/);if(target)return `Tarehe ya lengo / malipo: ${target[1]}`;
  const dates=text.match(/^(\d{4}-\d{2}-\d{2}) to (\d{4}-\d{2}-\d{2})$/);if(dates)return `${dates[1]} hadi ${dates[2]}`;
  const status=text.match(/^ · (pending|cancelled)$/);if(status)return ` · ${sw[status[1]]}`;
  const selection=text.match(/^ · (\d+) selected$/);if(selection)return ` · ${selection[1]} imechaguliwa`;
  const imported=text.match(/^Imported (\d+) records; skipped (\d+) duplicates$/);if(imported)return `Rekodi ${imported[1]} zimeingizwa; nakala ${imported[2]} zilizorudiwa zimerukwa`;
  const insight=text.match(/^You have recorded (\d+) transactions\. (.+)$/);if(insight){const category=insight[2].match(/^(.+) is your largest spending category this period\.$/);return `Umerekodi miamala ${insight[1]}. ${category?`${sw[category[1]]||category[1]} ndilo kundi lenye matumizi makubwa zaidi kipindi hiki.`:'Endelea kurekodi ili kuelewa mwenendo wa matumizi yako.'}`}
  return text;
}
